from __future__ import annotations

import asyncio
import json
import logging
import os
from typing import TYPE_CHECKING

from furrow.agents.prompts import TESTER_PROMPT
from furrow.config import TaskModel, TestResult
from furrow.llm import LLMClient

if TYPE_CHECKING:
    from furrow.config import Settings

logger = logging.getLogger(__name__)


class TesterAgent:
    """Agent responsible for executing tests and interpreting results."""

    JSON_PARSE_RETRIES = 2
    JSON_PARSE_RETRY_DELAY_SECONDS = 0.5
    DEFAULT_TEST_TIMEOUT_SECONDS = 120

    def __init__(self, client: LLMClient | None = None, settings: Settings | None = None) -> None:
        """Initialize the tester agent with an optional LLM client and settings."""
        self.client = client or LLMClient(settings=settings)

    async def run(self, goal: str, tasks: list[TaskModel]) -> TestResult:
        """Run tests for the given goal and tasks, returning structured results.

        Args:
            goal: The overall implementation goal.
            tasks: The list of tasks generated by the planner.

        Returns:
            A TestResult with pass/fail status, summary, and any failures.

        Raises:
            ValueError: If the LLM response cannot be parsed as valid JSON after retries.
        """
        test_output = ""
        try:
            test_output = await self._run_tests()
        except Exception as e:
            logger.exception("Error running tests")
            return TestResult(passed=False, summary=str(e), failures=[str(e)])

        prompt = f"{TESTER_PROMPT}\n\nGoal: {goal}\n\nTest output:\n{test_output}\n"
        response = await self.client.complete(prompt, model=self.client.settings.tester_model)

        data = None
        last_error = None
        for attempt in range(1, self.JSON_PARSE_RETRIES + 1):
            try:
                data = json.loads(response)
                break
            except (json.JSONDecodeError, ValueError) as e:
                last_error = e
                logger.warning("JSON parse failed on attempt %d/%d: %s", attempt, self.JSON_PARSE_RETRIES, e)
                if attempt < self.JSON_PARSE_RETRIES:
                    await asyncio.sleep(self.JSON_PARSE_RETRY_DELAY_SECONDS)
                    response = await self.client.complete(prompt, model=self.client.settings.tester_model)

        if data is None:
            raise ValueError(
                f"Failed to parse LLM response as JSON after {self.JSON_PARSE_RETRIES} attempts. "
                f"Last error: {last_error}. Raw response: {response!r}"
            )

        try:
            result = TestResult(**data)
            return result
        except (ValueError, TypeError) as e:
            logger.exception("Failed to validate parsed JSON against TestResult model")
            raise ValueError(
                f"Parsed JSON does not match TestResult schema: {e}. Raw data: {data!r}"
            ) from e

    def _get_test_command(self) -> list[str]:
        """Determine the appropriate test command based on project configuration files.

        Checks for common project config files in the current working directory
        and returns a test command appropriate for the project type.

        Returns:
            A list of command arguments to run tests, or an empty list if no
            suitable test runner is detected.
        """
        workspace = self.client.settings.workspace
        has_pyproject = (workspace / "pyproject.toml").is_file()
        has_setup_py = (workspace / "setup.py").is_file()
        has_setup_cfg = (workspace / "setup.cfg").is_file()
        has_package_json = (workspace / "package.json").is_file()
        has_cargo_toml = (workspace / "Cargo.toml").is_file()
        has_go_mod = (workspace / "go.mod").is_file()

        if has_pyproject or has_setup_py or has_setup_cfg:
            logger.info("Detected Python project (pyproject.toml/setup.py/setup.cfg)")
            return ["pytest", "-q"]

        if has_package_json:
            logger.info("Detected Node.js project (package.json)")
            return ["npm", "test", "--", "--silent"]

        if has_cargo_toml:
            logger.info("Detected Rust project (Cargo.toml)")
            return ["cargo", "test", "-q"]

        if has_go_mod:
            logger.info("Detected Go project (go.mod)")
            return ["go", "test", "./..."]

        logger.info("No project config file detected")
        return []

    async def _run_tests(self) -> str:
        """Execute the project's test suite and capture output.

        Determines the appropriate test command based on project configuration
        files, falls back to `pytest -q` if available, and handles timeouts.

        Returns:
            The combined stdout/stderr output from the test run, or a message
            indicating no test runner was found.
        """
        command = self._get_test_command()

        if not command:
            command = ["pytest", "-q"]
            logger.info("No project config found, attempting fallback to pytest")

        candidates = [command] if command else []

        for cmd in candidates or []:
            try:
                proc = await asyncio.create_subprocess_exec(
                    *cmd,
                    stdout=asyncio.subprocess.PIPE,
                    stderr=asyncio.subprocess.PIPE,
                )
                try:
                    stdout, stderr = await asyncio.wait_for(
                        proc.communicate(), timeout=self.DEFAULT_TEST_TIMEOUT_SECONDS
                    )
                    output = stdout.decode() + stderr.decode()
                    if output.strip():
                        logger.info("Test command completed: %s", cmd)
                    else:
                        logger.info("Test command completed with no output: %s", cmd)
                    return output
                except asyncio.TimeoutError:
                    logger.warning("Test command timed out after %ds: %s", self.DEFAULT_TEST_TIMEOUT_SECONDS, cmd)
                    proc.kill()
                    try:
                        stdout, stderr = await proc.communicate()
                    except Exception:
                        stdout, stderr = b"", b""
                    partial = stdout.decode() + stderr.decode()
                    return (
                        partial
                        + f"\n[timeout] Test command timed out after "
                        f"{self.DEFAULT_TEST_TIMEOUT_SECONDS}s: {' '.join(cmd)}"
                    )
            except (FileNotFoundError, Exception) as e:
                logger.debug("Test command failed: %s (%s)", cmd, e)
                continue

        return "No test runner found. Install pytest or configure tests in pyproject.toml"
