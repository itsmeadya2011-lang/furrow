def extract_json(text: str) -> str:
    """Extract the first JSON object from an LLM response, stripping markdown fences."""
    stripped = text.strip()
    # Strip markdown code fences if present.
    fence = re.search(r"```(?:json)?\s*\n?(.*?)\n?```", stripped, re.DOTALL)
    if fence:
        stripped = fence.group(1).strip()
    # If the whole response is a JSON object, return it.
    # (The balanced scan below handles this case correctly too, including
    # trailing prose after the object, so no fast path is needed.)
    start = stripped.find("{")
    if start == -1:
        raise ValueError("No JSON object found in response")
    depth = 0
    in_string = False
    escape = False
    for i in range(start, len(stripped)):
        ch = stripped[i]
        if in_string:
            if escape:
                escape = False
            elif ch == "\\":
                escape = True
            elif ch == '"':
                in_string = False
            continue
        if ch == '"':
            in_string = True
        elif ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                return stripped[start : i + 1]
    raise ValueError("Unterminated JSON object in response")
