import json
import re

import pytest

from furrow.agents.worker import WorkerAgent
from furrow.config import TaskModel
from furrow.llm import extract_json


class FakeSettings:
    worker_model = "fake-worker-model"


class FakeLLMClient:
    """In-memory stand-in for LLMClient that records reads/writes."""

    def __init__(self) -> None:
        self.files: dict[str, str] = {}
        self.writes: list[str] = []
        self.reads: list[str] = []
        self.settings = FakeSettings()

    async def read_file(self, path: str) -> str:
        self.reads.append(path)
        if path in self.files:
            return self.files[path]
        raise FileNotFoundError(path)

    async def write_file(self, path: str, content: str) -> None:
        self.writes.append(path)
        self.files[path] = content

    async def complete(self, prompt: str, model: str | None = None) -> str:
        # Simulate an LLM that returns full new content for every file section
        # referenced in the prompt (existing files get their content echoed back
        # with a marker; new files get default generated content).
        result: dict[str, str] = {}
        paths = re.findall(r"---\s*(.+?)\s*---\n", prompt)
        for path in paths:
            path = path.strip()
            if path in self.files:
                result[path] = self.files[path] + "\n# modified by worker\n"
            else:
                result[path] = f"# {path}\n# generated by worker\n"
        return json.dumps(result)


@pytest.mark.asyncio
async def test_worker_writes_existing_file():
    client = FakeLLMClient()
    client.files["src/foo.py"] = "def foo():\n    pass\n"
    task = TaskModel(id="1", description="add docstring", files=["src/foo.py"])
    worker = WorkerAgent(task=task, client=client)

    result = await worker.run()

    assert "src/foo.py" in client.reads
    assert "src/foo.py" in client.writes
    assert client.files["src/foo.py"].endswith("# modified by worker\n")
    assert "Wrote 1 file(s)" in result


@pytest.mark.asyncio
async def test_worker_creates_new_file():
    client = FakeLLMClient()
    task = TaskModel(id="1", description="create bar module", files=["src/bar.py"])
    worker = WorkerAgent(task=task, client=client)

    await worker.run()

    assert "src/bar.py" in client.reads
    assert "src/bar.py" in client.writes
    assert client.files["src/bar.py"].endswith("# generated by worker\n")


@pytest.mark.asyncio
async def test_worker_writes_multiple_files():
    client = FakeLLMClient()
    client.files["src/a.py"] = "a = 1\n"
    client.files["src/b.py"] = "b = 2\n"
    task = TaskModel(id="1", description="touch two files", files=["src/a.py", "src/b.py"])
    worker = WorkerAgent(task=task, client=client)

    await worker.run()

    assert set(client.writes) == {"src/a.py", "src/b.py"}
    assert client.files["src/a.py"].endswith("# modified by worker\n")
    assert client.files["src/b.py"].endswith("# modified by worker\n")


def test_extract_json_plain():
    assert extract_json('{"a": 1}') == {"a": 1}


def test_extract_json_markdown_fence():
    text = '```json\n{"b": 2}\n```'
    assert extract_json(text) == {"b": 2}


def test_extract_json_ignores_fenced_code_without_json_label():
    text = "Here is the result:\n```\n{\"c\": 3}\n```\nDone."
    assert extract_json(text) == {"c": 3}
